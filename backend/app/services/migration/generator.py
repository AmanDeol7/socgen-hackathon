"""Deterministic, safe materialisation of generated EUC files."""

from __future__ import annotations

from pathlib import Path, PurePosixPath

from app.schemas.migration import CodeAnalysis, EucMetadata, GeneratedEUC, GeneratedFile
from app.services.migration.runtime import RUNNER_CONTENT

_STANDARD_FILES = {
    "src/runner.py",
    "Dockerfile",
    "config/config.yaml",
    "requirements.txt",
    "README.md",
}
_STDLIB_MODULES = {
    "argparse", "ast", "base64", "collections", "datetime", "email", "functools",
    "hashlib", "http", "io", "itertools", "json", "logging", "math", "os",
    "pathlib", "re", "secrets", "shutil", "sqlite3", "string",
    "subprocess", "sys", "tempfile", "textwrap", "time", "typing", "unittest",
    "urllib", "uuid", "warnings",
}


def generate(generated_euc: GeneratedEUC, output_dir: str | Path) -> list[Path]:
    """Write an EUC below ``output_dir`` and return paths in input order.

    All paths are checked before any file is created.  This prevents a malformed
    response from producing a partially written EUC.
    """
    paths = _validated_paths(generated_euc)
    destination = Path(output_dir).resolve()
    destination.mkdir(parents=True, exist_ok=True)
    targets = _resolved_targets(destination, paths)
    written: list[Path] = []
    for generated_file, target in zip(generated_euc.files, targets):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generated_file.content, encoding="utf-8", newline="")
        written.append(target)
    return written


def generate_euc(generated_euc: GeneratedEUC, output_dir: str | Path) -> list[Path]:
    """Descriptive alias for :func:`generate`."""
    return generate(generated_euc, output_dir)


def assemble(
    business_euc: GeneratedEUC,
    metadata: EucMetadata,
    analysis: CodeAnalysis,
) -> GeneratedEUC:
    """Assemble business files with platform-owned standardized files."""
    business_files = [
        generated_file
        for generated_file in business_euc.files
        if generated_file.path not in _STANDARD_FILES
    ]
    files = [
        *business_files,
        GeneratedFile(path="src/runner.py", content=RUNNER_CONTENT),
        GeneratedFile(path="Dockerfile", content=_dockerfile(metadata.python_version)),
        GeneratedFile(path="config/config.yaml", content=_config(metadata)),
        GeneratedFile(path="requirements.txt", content=_requirements(metadata, analysis)),
        GeneratedFile(path="README.md", content=_readme(metadata, business_euc)),
    ]
    return business_euc.model_copy(update={"files": files})


def _dockerfile(python_version: str) -> str:
    return f"""FROM python:{python_version}-slim
WORKDIR /app
COPY requirements.txt requirements.txt
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
ENTRYPOINT ["python", "-m", "src.runner"]
"""


def _config(metadata: EucMetadata) -> str:
    lines = ["secret_references:"]
    if metadata.secret_references:
        for reference in metadata.secret_references:
            lines.extend(
                [
                    f"  {reference.name}:",
                    f"    vault: {_yaml_value(reference.vault)}",
                    f"    key: {_yaml_value(reference.key)}",
                ]
            )
    else:
        lines.append("  {}")
    return "\n".join(lines) + "\n"


def _requirements(metadata: EucMetadata, analysis: CodeAnalysis) -> str:
    dependencies = metadata.dependencies or _inferred_dependencies(analysis)
    unique = list(dict.fromkeys(dependency.strip() for dependency in dependencies if dependency.strip()))
    return (
        "\n".join(sorted(unique)) + "\n"
        if unique
        else "# No external dependencies required\n"
    )


def _inferred_dependencies(analysis: CodeAnalysis) -> list[str]:
    return [
        module.split(".", 1)[0]
        for module in analysis.imports
        if module.split(".", 1)[0] not in _STDLIB_MODULES
        and not module.startswith("sglambdautils")
    ]


def _readme(metadata: EucMetadata, business_euc: GeneratedEUC) -> str:
    dependencies = metadata.dependencies or ["inferred from analyzed imports"]
    warnings = business_euc.warnings + business_euc.unsupported_features
    warning_text = "\n".join(f"- {warning}" for warning in warnings) or "- None"
    return f"""# {metadata.name}

{metadata.description or "Standardized EUC generated by the EUC Platform."}

## Execution

The EUC reads one JSON object from stdin and writes one JSON object plus a
newline to stdout through `python -m src.runner`.

## Dependencies

{", ".join(dependencies)}

## Secret references

{len(metadata.secret_references)} reference(s) are configured without storing secret values.

## Warnings and unsupported features

{warning_text}
"""


def _yaml_value(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _validated_paths(generated_euc: GeneratedEUC) -> list[PurePosixPath]:
    seen: set[str] = set()
    validated: list[PurePosixPath] = []
    for generated_file in generated_euc.files:
        path = generated_file.path
        if not path:
            raise ValueError("Generated EUC contains an empty file path.")
        pure = PurePosixPath(path)
        if (
            pure.is_absolute()
            or path != pure.as_posix()
            or ".." in pure.parts
            or "\\" in path
            or not pure.parts
        ):
            raise ValueError(f"Generated EUC contains an unsafe file path: {path!r}.")
        if path in seen:
            raise ValueError(f"Generated EUC contains a duplicate file path: {path!r}.")
        seen.add(path)
        validated.append(pure)
    return validated


def _resolved_targets(
    destination: Path, paths: list[PurePosixPath]
) -> list[Path]:
    """Resolve targets and reject symlink or traversal escapes."""
    targets: list[Path] = []
    for relative in paths:
        target = destination.joinpath(*relative.parts).resolve()
        try:
            target.relative_to(destination)
        except ValueError as error:
            raise ValueError(
                f"Generated EUC path escapes the destination: {relative.as_posix()!r}."
            ) from error
        targets.append(target)
    return targets
